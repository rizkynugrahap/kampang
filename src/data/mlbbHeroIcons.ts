/**
 * Returns the official icon URL for any MLBB hero with normalization
 */
export function getHeroIconUrl(heroName?: string): string {
  if (!heroName) return "";
  const trimmed = heroName.trim();
  
  // Exact match
  if (MLBB_HERO_ICONS[trimmed]) {
    return MLBB_HERO_ICONS[trimmed];
  }

  // Case-insensitive match
  const lower = trimmed.toLowerCase();
  const foundKey = Object.keys(MLBB_HERO_ICONS).find(k => k.toLowerCase() === lower);
  if (foundKey) {
    return MLBB_HERO_ICONS[foundKey];
  }

  // Partial or fuzzy match (e.g. "Popol" -> "Popol and Kupa")
  const partialKey = Object.keys(MLBB_HERO_ICONS).find(k => 
    k.toLowerCase().includes(lower) || lower.includes(k.toLowerCase())
  );
  if (partialKey) {
    return MLBB_HERO_ICONS[partialKey];
  }

  return "";
}
